def test_python_ternary_dot():
    print("[1] Testing Python Ternary Dot Product...")
    # Packed format: 2 bits per trit (01 = +1, 10 = -1, 00 = 0)
    # 0x55555555 has all 16 trits as +1
    a = 0x55555555
    b = 0x55555555

    lo_a = a & 0x55555555
    hi_a = (a >> 1) & 0x55555555
    pos_a = lo_a & ~hi_a
    neg_a = ~lo_a & hi_a

    lo_b = b & 0x55555555
    hi_b = (b >> 1) & 0x55555555
    pos_b = lo_b & ~hi_b
    neg_b = ~lo_b & hi_b

    plus = (pos_a & pos_b) | (neg_a & neg_b)
    minus = (pos_a & neg_b) | (neg_a & pos_b)
    dot = bin(plus).count("1") - bin(minus).count("1")

    assert dot == 16, f"Expected 16, got {dot}"
    print(f"    [PASS] Ternary dot product: {dot} (Exact bitwise match)")


