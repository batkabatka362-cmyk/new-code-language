def build_expert_dataset():
    base_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))
    corpus_file = os.path.join(base_dir, "crates", "cronc", "src", "cl_sovereign_corpus.rs")
    
    entries = []

    # 1. Load original dialogues
    if os.path.exists(corpus_file):
        with open(corpus_file, "r", encoding="utf-8", errors="ignore") as f:
            content = f.read()
        pattern = re.compile(r'\(\s*"([^"]+)"\s*,\s*"([^"]+)"\s*\)')
        for q, a in pattern.findall(content):
            entries.append((q, a))

    # 2. Add expert multi-domain knowledge
    for q, a in EXPERT_KNOWLEDGE:
        entries.append((q, a))

    # Format JSONL
    out_file = os.path.join(base_dir, "python", "tetra_train", "sovereign_expert_dataset.jsonl")
    with open(out_file, "w", encoding="utf-8") as f:
        for q, a in entries:
            doc = {
                "instruction": q,
                "response": a,
                "text": f"<|im_start|>user\n{q}<|im_end|>\n<|im_start|>assistant\n{a}<|im_end|>\n"
            }
            f.write(json.dumps(doc, ensure_ascii=False) + "\n")

    print(f"[+] Нийт {len(entries)} ширхэг мэргэжлийн түвшний гүн харилцан яриа бүхий датасет үүслээ: {out_file}")
    return out_file

if __name__ == "__main__":
    build_expert_dataset()
