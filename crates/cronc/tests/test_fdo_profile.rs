#[test]
fn test_fdo_full_roundtrip_compile_and_recompile() {
    // 1. Compile source to .cl
    let cl_code = compile_source(sample_cr_program())
        .expect("Initial compilation failed");
    assert!(!cl_code.is_empty(), "CL output must not be empty");

    // 2. Recompile with FDO profile
    let prof = sample_fdo_profile();
    let (optimized, analysis) = fdo_recompile(&cl_code, &prof)
        .expect("FDO recompilation failed");

    // 3. Verify optimized output is valid
    assert!(!optimized.is_empty(), "Optimized CL must not be empty");
    assert!(
        optimized.contains("B0000:"),
        "Must contain at least one bundle"
    );

    // 4. Verify analysis report
    assert!(analysis.original_cycles > 0, "Must report original cycle count");
}

#[test]
fn test_fdo_recompile_reduces_nop_count() {
    // Generate a CL program with intentionally NOP-heavy bundles
    let nop_heavy_cl = r#"
    B0000: '=00#000A> '=01#0005> _PO02$100> _SH00$000>
    B0001: _PO03$200> _NO00#000> _NO00#000> _NO00#000>
    B0002: _PO04$300> _NO00#000> _NO00#000> _NO00#000>
    B0003: _GU05$200> _NO00#000> _NO00#000> _HL00$000!
    "#;

    let prof = r#"; CRON FDO Execution Profile v1.0
; Total Bundles: 4
; Total NOPs: 9
; Avg Slot Utilization: 0.4375
; Hottest Bundle: B0000
; Underutilized Bundles: 3

[OPCODE_FREQUENCY]
  PO = 3
  NO = 9
  GU = 1
  HL = 1
  SH = 1

[BUNDLE_PROFILES]
  B0000: exec=1 nops=0 optical_stall=false raw_stall=false
  B0001: exec=10 nops=3 optical_stall=false raw_stall=false
  B0002: exec=10 nops=3 optical_stall=false raw_stall=false
  B0003: exec=1 nops=3 optical_stall=false raw_stall=false
"#;

    let (optimized, _analysis) = fdo_recompile(nop_heavy_cl, prof)
        .expect("FDO recompilation failed");

    assert!(!optimized.is_empty(), "Optimized output must not be empty");

    // Count bundles in optimized output
    let optimized_bundles = optimized.lines()
        .filter(|l| l.trim().starts_with('B'))
        .count();

    // The optimized version should have fewer or equal bundles
    assert!(
        optimized_bundles <= 4,
        "FDO should not increase bundle count (got {} from 4)",
        optimized_bundles
    );
}

#[test]
fn test_fdo_analysis_summary_format() {
    let prof = parse_fdo_profile(&sample_fdo_profile()).expect("Parse failed");
    let analysis = analyze_profile(&prof);
    let summary = analysis.summary();
    assert!(summary.contains("[FDO]"), "Summary must have FDO prefix");
    assert!(summary.contains("Hot bundles"), "Summary must report hot bundles");
    assert!(summary.contains("Cold bundles"), "Summary must report cold bundles");
    assert!(summary.contains("NOP-heavy"), "Summary must report NOP-heavy bundles");
}

#[test]
fn test_fdo_compile_source_with_fdo_api() {
    let prof = sample_fdo_profile();
    let result = cronc::compile_source_with_fdo(sample_cr_program(), &prof);
    assert!(result.is_ok(), "compile_source_with_fdo should succeed: {:?}", result.err());
    let optimized = result.unwrap();
    assert!(!optimized.is_empty(), "FDO-optimized output must not be empty");
}
