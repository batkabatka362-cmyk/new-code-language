use cronc::compile_source;
use cronc::fdo::{parse_fdo_profile, analyze_profile, fdo_recompile};

fn sample_cr_program() -> &'static str {
    r#"
    .MODULE FDOTest
    .ENTRY _main

    def compute(a: u32, b: u32) -> u32 {
        let sum = a + b
        let product = a * b
        return sum + product
    }

    _main:
        let x = compute(10, 20)
        let y = compute(x, 5)
        export y as result_y
    .END
    "#
}

fn sample_fdo_profile() -> String {
    r#"; CRON FDO Execution Profile v1.0
; Generated by cron-vm 4D-Torus Simulator
; Total Bundles: 6
; Total NOPs: 12
; Avg Slot Utilization: 0.5000
; Hottest Bundle: B0003
; Underutilized Bundles: 3

[OPCODE_FREQUENCY]
  PO = 8
  NO = 12
  OP = 2
  HL = 1
  FA = 1
  GU = 2

[BUNDLE_PROFILES]
  B0000: exec=1 nops=0 optical_stall=false raw_stall=false
  B0001: exec=1 nops=0 optical_stall=false raw_stall=false
  B0002: exec=50 nops=1 optical_stall=false raw_stall=false
  B0003: exec=200 nops=0 optical_stall=true raw_stall=true
  B0004: exec=1 nops=3 optical_stall=false raw_stall=false
  B0005: exec=1 nops=3 optical_stall=false raw_stall=false
"#
    .to_string()
}

// ============================================================================
// Profile Parsing Tests
// ============================================================================

#[test]
fn test_fdo_parse_profile_metadata() {
    let prof = parse_fdo_profile(&sample_fdo_profile()).expect("Parse failed");
    assert_eq!(prof.total_nops, 12);
    assert!((prof.avg_slot_utilization - 0.5).abs() < 0.01);
    assert_eq!(prof.hottest_bundle_cycle, 3);
    assert_eq!(prof.underutilized_bundles, 3);
}

#[test]
fn test_fdo_parse_profile_opcode_frequencies() {
    let prof = parse_fdo_profile(&sample_fdo_profile()).expect("Parse failed");
    assert_eq!(*prof.opcode_frequency.get("PO").unwrap_or(&0), 8);
    assert_eq!(*prof.opcode_frequency.get("NO").unwrap_or(&0), 12);
    assert_eq!(*prof.opcode_frequency.get("OP").unwrap_or(&0), 2);
    assert_eq!(*prof.opcode_frequency.get("GU").unwrap_or(&0), 2);
}

#[test]
fn test_fdo_parse_profile_bundle_entries() {
    let prof = parse_fdo_profile(&sample_fdo_profile()).expect("Parse failed");
    assert_eq!(prof.bundle_entries.len(), 6);
    assert_eq!(prof.bundle_entries[3].exec_count, 200);
    assert!(prof.bundle_entries[3].had_optical_stall);
    assert!(prof.bundle_entries[3].had_raw_stall);
    assert_eq!(prof.bundle_entries[4].nop_count, 3);
}

#[test]
fn test_fdo_parse_empty_profile_rejected() {
    let result = parse_fdo_profile("");
    assert!(result.is_err(), "Empty profile should be rejected");
}

