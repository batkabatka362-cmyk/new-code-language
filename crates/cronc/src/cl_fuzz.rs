/// Run autonomous AI Vibe-Fuzzing loop
pub fn run_cl_fuzz(options: &FuzzOptions) -> ClFuzzReport {
    let mut rng = XorShift64::new(options.seed);
    let mut report = ClFuzzReport {
        total_iterations: options.iterations,
        seed_used: options.seed,
        ..Default::default()
    };

    let base_seed = options.seed_code.clone().unwrap_or_else(|| get_default_fuzz_seed().to_string());

    for _ in 0..options.iterations {
        let num_mutations = 1 + rng.next_usize(options.max_mutations_per_cycle);
        let mut mutant = base_seed.clone();

        for _ in 0..num_mutations {
            mutant = apply_random_mutation(&mutant, &mut rng);
            report.mutations_applied += 1;
        }

        // Catch any possible panic across the entire compiler toolchain
        let test_jit = options.test_jit_execution;
        let test_opt = options.test_optimizer;
        let test_mem = options.test_memcheck;

        let result = catch_unwind(AssertUnwindSafe(|| {
            // 1. Self-healing parser
            match heal_cl_program(&mutant) {
                Ok(healed) => {
                    let mut code_to_run = healed.canonical_code;

                    // 2. Super-optimizer
                    if test_opt {
                        let opt_cfg = ClOptConfig::default();
                        if let Ok(opt_res) = optimize_cl_program_advanced(&code_to_run, &opt_cfg) {
                            code_to_run = opt_res.optimized_code;
                        }
                    }

                    // 3. Memory bank verifier
                    let mut had_mem_hazard = false;
                    if test_mem {
                        let mem_opts = MemcheckOptions {
                            strict_mode: false,
                            ..Default::default()
                        };
                        if let Ok(mem_rep) = verify_cl_memory_access(&code_to_run, &mem_opts) {
                            if !mem_rep.is_provably_conflict_free {
                                had_mem_hazard = true;
                            }
                        }
                    }

                    // 4. JIT Silicon execution
                    let executed = if test_jit {
                        let mut core = crate::cl_jit::ClJitCore::new();
                        execute_cl_on_core(&code_to_run, &mut core).is_ok()
                    } else {
                        false
                    };

                    (true, executed, had_mem_hazard)
                }
                Err(_) => {
                    // Graceful rejection is valid compiler behavior
                    (false, false, false)
                }
            }
        }));

        match result {
            Ok((healed, executed, mem_hazard)) => {
                if healed {
                    report.auto_healed_count += 1;
                    if test_opt {
                        report.optimized_count += 1;
                    }
                    if executed {
                        report.successfully_executed_count += 1;
                    }
                    if mem_hazard {
                        report.memory_hazards_caught += 1;
                    }
                } else {
                    report.gracefully_rejected_count += 1;
                }
            }
            Err(_) => {
                report.unhandled_panics += 1;
                if report.crash_samples.len() < 5 {
                    report.crash_samples.push(mutant.clone());
                }
            }
        }
    }

    report
}

/// Applies a selected stochastic mutation to a `.cl` source string
fn apply_random_mutation(source: &str, rng: &mut XorShift64) -> String {
    let strategies = [
        MutationStrategy::BitFlip,
        MutationStrategy::SlotPermute,
        MutationStrategy::RegisterAliasing,
        MutationStrategy::ImmediateExtremes,
        MutationStrategy::CRCCorruption,
        MutationStrategy::RandomSlotInjection,
        MutationStrategy::BundleTruncation,
        MutationStrategy::TorusCoordMutation,
        MutationStrategy::BankConflictInjection,
    ];

    let strat = strategies[rng.next_usize(strategies.len())];

    match strat {
        MutationStrategy::BitFlip => {
            let mut bytes = source.as_bytes().to_vec();
            if !bytes.is_empty() {
                let idx = rng.next_usize(bytes.len());
                bytes[idx] = rng.next_char_ascii() as u8;
            }
            String::from_utf8_lossy(&bytes).to_string()
        }
        MutationStrategy::SlotPermute => {
            let mut lines: Vec<String> = source.lines().map(|s| s.to_string()).collect();
            for line in &mut lines {
                if let Some((b_part, slots_part)) = line.split_once(':') {
                    let mut slots: Vec<&str> = slots_part.split_whitespace().collect();
                    if slots.len() > 1 {
                        let i = rng.next_usize(slots.len());
                        let j = rng.next_usize(slots.len());
                        slots.swap(i, j);
                        *line = format!("{}: {}", b_part, slots.join(" "));
                    }
                }
            }
            lines.join("\n")
        }
        MutationStrategy::RegisterAliasing => {
            // Force multiple slots to write to R0
            source.replace("01", "00").replace("02", "00").replace("03", "00")
        }
        MutationStrategy::ImmediateExtremes => {
            let extremes = ["#000", "#FFF", "#7FF", "#800", "#001"];
            let picked = extremes[rng.next_usize(extremes.len())];
            if source.contains('#') {
                source.replacen("#004", picked, 1)
            } else {
                source.to_string()
            }
        }
        MutationStrategy::CRCCorruption => {
            // Corrupt the last character before delimiter '>'
            let mut chars: Vec<char> = source.chars().collect();
            let mut gt_indices: Vec<usize> = Vec::new();
            for (i, &c) in chars.iter().enumerate() {
                if c == '>' && i > 0 {
                    gt_indices.push(i - 1);
                }
            }
            if !gt_indices.is_empty() {
                let target = gt_indices[rng.next_usize(gt_indices.len())];
                chars[target] = rng.next_char_ascii();
            }
            chars.into_iter().collect()
        }
        MutationStrategy::RandomSlotInjection => {
            let ops = ["_OP", "_FA", "_PO", "_MD", "_BK", "_ST", "_TT", "_NO", "_HL"];
            let modes = ['$', '*', '+', '-', '.', '/', '&', '|', '#', '!'];
            let op = ops[rng.next_usize(ops.len())];
            let mode = modes[rng.next_usize(modes.len())];
            let reg = rng.next_usize(16);
            let imm = rng.next_usize(4096);
            let random_slot = format!("{}{:02X}{}{:03X}>", op, reg, mode, imm);
            format!("{}\nB9999: {} _NO00#000> _NO00#000> _NO00#000>", source, random_slot)
        }
        MutationStrategy::BundleTruncation => {
            let mut lines: Vec<&str> = source.lines().collect();
            if lines.len() > 2 {
                let remove_idx = rng.next_usize(lines.len());
                lines.remove(remove_idx);
            }
            lines.join("\n")
        }
        MutationStrategy::TorusCoordMutation => {
            let x = rng.next_usize(8);
            let y = rng.next_usize(8);
            let z = rng.next_usize(8);
            let w = rng.next_usize(8);
            format!(".core [{}, {}, {}, {}]:\n{}", x, y, z, w, source)
        }
        MutationStrategy::BankConflictInjection => {
            // Injects concurrent stores targeting identical SRAM address 0x40
            let conflict_bundle = "B8888: _ST00#040> _ST00#040> _NO00#000> _NO00#000>\n";
            format!("{}{}", conflict_bundle, source)
        }
    }
}
