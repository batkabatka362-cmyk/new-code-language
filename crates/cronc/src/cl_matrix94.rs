//! `cl_matrix94`: 4-Tact Pipelined Engine for the 94 x 94 x 94 x 94 Discrete AI State Space.
//!
//! Based on DPSTA & Topological Brain Transformer (TBT) specification (matrix4.1.2.pdf).
//!
//! Features:
//!   - 4 Cascaded Transition Matrices (M1, M2, M3, M4) = 4 x 94 x 94 = 35,344 bytes (~35.3 KB L1 Cache footprint).
//!   - Zero-FLOPs bitwise state transition & tropical semiring (max, +) accumulation.
//!   - Homeostatic soft-decay regulation: prevents saturation at 255.
//!   - Rigorous hardware-level 4-stage pipeline registers maintaining exact state history.
//!   - Cayley Quasigroup Latin Square algebraic foundations (gcd(alpha, 94) = 1).

use std::fmt;

pub const NUM_STATES: usize = 94;
pub const ASCII_START: u8 = 33; // '!'
pub const ASCII_END: u8 = 126;   // '~'
pub const BUDGET_MAX: u32 = 1024;
pub const MATRIX_STAGE_SIZE: usize = NUM_STATES * NUM_STATES; // 8,836
pub const TOTAL_STAGES: usize = 4;
pub const FOUR_TACT_SIZE: usize = TOTAL_STAGES * MATRIX_STAGE_SIZE; // 35,344 bytes

/// Converts a printable character to discrete state ID (0..93).
#[inline(always)]
pub fn char_to_state(ch: char) -> u8 {
    let byte = ch as u32;
    if (ASCII_START as u32..=ASCII_END as u32).contains(&byte) {
        (byte - ASCII_START as u32) as u8
    } else {
        0
    }
}

/// Converts a discrete state ID (0..93) back to a printable ASCII character.
#[inline(always)]
pub fn state_to_char(state: u8) -> char {
    ((state as usize % NUM_STATES) as u8 + ASCII_START) as char
}

/// Computes the Cayley Quasigroup Latin Square cell:
/// (alpha * a + beta * b + gamma) % 94
#[inline(always)]
pub fn cayley_cell(alpha: u32, beta: u32, gamma: u32, a: u8, b: u8) -> u8 {
    ((alpha * (a as u32) + beta * (b as u32) + gamma) % (NUM_STATES as u32)) as u8
}

/// Validates that a Latin Square generated by (alpha, beta, gamma) has no duplicate rows or columns.
pub fn verify_latin_square(alpha: u32, beta: u32, gamma: u32) -> bool {
    fn gcd(mut a: u32, mut b: u32) -> u32 {
        while b != 0 {
            let t = b;
            b = a % b;
            a = t;
        }
        a
    }
    if gcd(alpha, NUM_STATES as u32) != 1 || gcd(beta, NUM_STATES as u32) != 1 {
        return false;
    }

    let mut row_seen = [false; NUM_STATES];
    let mut col_seen = [false; NUM_STATES];

    for i in 0..NUM_STATES {
        row_seen.fill(false);
        col_seen.fill(false);
        for j in 0..NUM_STATES {
            let cell_r = cayley_cell(alpha, beta, gamma, i as u8, j as u8) as usize;
            if row_seen[cell_r] {
                return false;
            }
            row_seen[cell_r] = true;

            let cell_c = cayley_cell(alpha, beta, gamma, j as u8, i as u8) as usize;
            if col_seen[cell_c] {
                return false;
            }
            col_seen[cell_c] = true;
        }
    }
    true
}

/// Stage 1 Pipeline Register: Ingestion & Decode.
#[derive(Debug, Clone, Default)]
pub struct StageReg1 {
    pub valid: bool,
    pub char: char,
    pub state: u8,
}

/// Stage 2 Pipeline Register: Bigram M1 + Trigram Permutation wire-shift.
#[derive(Debug, Clone)]
pub struct StageReg2 {
    pub valid: bool,
    pub char: char,
    pub state: u8,
    pub prev_state: u8,
    pub scores: [i32; NUM_STATES],
}

impl Default for StageReg2 {
    fn default() -> Self {
        Self {
            valid: false,
            char: '\0',
            state: 0,
            prev_state: 0,
            scores: [0; NUM_STATES],
        }
    }
}

/// Stage 3 Pipeline Register: 4-Gram Rotor Sandwich & Tropical Sum.
#[derive(Debug, Clone)]
pub struct StageReg3 {
    pub valid: bool,
    pub char: char,
    pub state: u8,
    pub prev_state: u8,
    pub prev_state2: u8,
    pub scores: [i32; NUM_STATES],
}

impl Default for StageReg3 {
    fn default() -> Self {
        Self {
            valid: false,
            char: '\0',
            state: 0,
            prev_state: 0,
            prev_state2: 0,
            scores: [0; NUM_STATES],
        }
    }
}

/// Stage 4 Pipeline Output: Argmax selection and emitted character.
#[derive(Debug, Clone, Default)]
pub struct PipelineOutput {
    pub cycle: u64,
    pub valid: bool,
    pub predicted_char: char,
    pub predicted_state: u8,
    pub score: i32,
}

/// 4-Tact Pipelined DPSTA Discrete Transition Engine.
#[derive(Clone)]
pub struct FourTactPipeline94 {
    /// Stage 1: Bigram transition matrix (c_{t-1} -> c_t)
    pub m_stage1: Box<[[u8; NUM_STATES]; NUM_STATES]>,
    /// Stage 2: Meso Trigram permutation resonance (c_{t-2} ^ (c_{t-1} << 1) -> c_t)
    pub m_stage2: Box<[[u8; NUM_STATES]; NUM_STATES]>,
    /// Stage 3: Macro 4-Gram Clifford Rotor resonance (c_{t-3} ^ (c_{t-2} << 1) ^ (c_{t-1} << 2) -> c_t)
    pub m_stage3: Box<[[u8; NUM_STATES]; NUM_STATES]>,
    /// Stage 4: Long-range feedback matrix
    pub m_stage4: Box<[[u8; NUM_STATES]; NUM_STATES]>,

    // Hardware Pipeline Registers
    pub pipe_stage1: StageReg1,
    pub pipe_stage2: StageReg2,
    pub pipe_stage3: StageReg3,

    // Clock and Statistics
    pub clk_cycle: u64,
    pub total_updates: u64,
    pub homeostatic_decays: u64,
}

impl fmt::Debug for FourTactPipeline94 {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("FourTactPipeline94")
            .field("clk_cycle", &self.clk_cycle)
            .field("total_updates", &self.total_updates)
            .field("homeostatic_decays", &self.homeostatic_decays)
            .finish()
    }
}

impl Default for FourTactPipeline94 {
    fn default() -> Self {
        Self::new()
    }
}

impl FourTactPipeline94 {
    pub fn new() -> Self {
        Self {
            m_stage1: Box::new([[0u8; NUM_STATES]; NUM_STATES]),
            m_stage2: Box::new([[0u8; NUM_STATES]; NUM_STATES]),
            m_stage3: Box::new([[0u8; NUM_STATES]; NUM_STATES]),
            m_stage4: Box::new([[0u8; NUM_STATES]; NUM_STATES]),
            pipe_stage1: StageReg1::default(),
            pipe_stage2: StageReg2::default(),
            pipe_stage3: StageReg3::default(),
            clk_cycle: 0,
            total_updates: 0,
            homeostatic_decays: 0,
        }
    }

    /// Resets the hardware pipeline registers without modifying weights.
    pub fn flush_pipeline(&mut self) {
        self.pipe_stage1 = StageReg1::default();
        self.pipe_stage2 = StageReg2::default();
        self.pipe_stage3 = StageReg3::default();
    }

    /// Applies Homeostatic Soft-Decay on a row if total weight exceeds budget:
    /// W[src, :] = W[src, :] - (W[src, :] >> 3)
    #[inline(always)]
    fn apply_homeostatic_decay(row: &mut [u8; NUM_STATES], decay_counter: &mut u64) {
        let row_sum: u32 = row.iter().map(|&w| w as u32).sum();
        if row_sum > BUDGET_MAX {
            *decay_counter += 1;
            for val in row.iter_mut() {
                if *val > 0 {
                    let decay = (*val >> 3).max(1);
                    *val = val.saturating_sub(decay);
                }
            }
        }
    }

    /// Trains transition weights across 4-tact representations with Homeostasis.
    pub fn train_sequence(&mut self, text: &str) {
        let chars: Vec<char> = text.chars().filter(|c| !c.is_control()).collect();
        if chars.len() < 2 {
            return;
        }

        for i in 0..chars.len() - 1 {
            let s0 = char_to_state(chars[i]);
            let s1 = char_to_state(chars[i + 1]);

            // Stage 1: Bigram update
            Self::apply_homeostatic_decay(&mut self.m_stage1[s0 as usize], &mut self.homeostatic_decays);
            self.m_stage1[s0 as usize][s1 as usize] =
                (self.m_stage1[s0 as usize][s1 as usize] as u16 + 10).min(255) as u8;

            // Stage 2: Meso Trigram wire-shift permutation update
            if i >= 1 {
                let s_prev = char_to_state(chars[i - 1]);
                let s_perm = (((s_prev as usize) ^ ((s0 as usize) << 1)) % NUM_STATES) as u8;
                Self::apply_homeostatic_decay(&mut self.m_stage2[s_perm as usize], &mut self.homeostatic_decays);
                self.m_stage2[s_perm as usize][s1 as usize] =
                    (self.m_stage2[s_perm as usize][s1 as usize] as u16 + 15).min(255) as u8;
            }

            // Stage 3: Macro 4-Gram Clifford Rotor update
            if i >= 2 {
                let s_prev = char_to_state(chars[i - 1]);
                let s_prev2 = char_to_state(chars[i - 2]);
                let s_rotor = (((s_prev2 as usize)
                    ^ ((s_prev as usize) << 1)
                    ^ ((s0 as usize) << 2))
                    % NUM_STATES) as u8;
                Self::apply_homeostatic_decay(&mut self.m_stage3[s_rotor as usize], &mut self.homeostatic_decays);
                self.m_stage3[s_rotor as usize][s1 as usize] =
                    (self.m_stage3[s_rotor as usize][s1 as usize] as u16 + 25).min(255) as u8;
            }

            self.total_updates += 1;
        }
    }

    /// Sharp-Wave Ripple (SWR) biological sleep consolidation cycle.
    /// Traverses dominant attractors across stages 1, 2, and 3, consolidating
    /// high-confidence trajectories into stage 4 (long-range neocortical matrix).
    pub fn sleep_replay_cycle(&mut self, ripples: usize) -> (usize, usize) {
        let mut reinforced = 0;
        for _ in 0..ripples {
            for s0 in 0..NUM_STATES {
                let mut best_s1 = 0;
                let mut max_w = 0u8;
                for s1 in 0..NUM_STATES {
                    if self.m_stage1[s0][s1] > max_w {
                        max_w = self.m_stage1[s0][s1];
                        best_s1 = s1;
                    }
                }
                if max_w > 15 {
                    self.m_stage1[s0][best_s1] = (self.m_stage1[s0][best_s1] as u16 + 2).min(255) as u8;
                    self.m_stage4[s0][best_s1] = (self.m_stage4[s0][best_s1] as u16 + 5).min(255) as u8;
                    reinforced += 1;
                }
            }
        }
        self.total_updates += reinforced as u64;
        (ripples, reinforced)
    }

    /// Advances the 4-Tact Hardware Pipeline by 1 clock cycle.
    /// All 4 stages compute concurrently.
    pub fn clock_tick(&mut self, in_valid: bool, in_char: char) -> PipelineOutput {
        self.clk_cycle += 1;

        // ---------------------------------------------------------------------
        // TACT 4 (CYCLE 4): ARGMAX & EMISSION (reads pipe_stage3)
        // ---------------------------------------------------------------------
        let mut out_result = PipelineOutput {
            cycle: self.clk_cycle,
            valid: false,
            predicted_char: ' ',
            predicted_state: 0,
            score: 0,
        };

        if self.pipe_stage3.valid {
            let mut best_state = 0usize;
            let mut best_score = i32::MIN;
            for (idx, &sc) in self.pipe_stage3.scores.iter().enumerate() {
                if sc > best_score {
                    best_score = sc;
                    best_state = idx;
                }
            }
            out_result.valid = true;
            out_result.predicted_state = best_state as u8;
            out_result.predicted_char = state_to_char(best_state as u8);
            out_result.score = best_score;
        }

        // ---------------------------------------------------------------------
        // TACT 3 (CYCLE 3): 3RD-ORDER 4-GRAM ROTOR SANDWICH & TROPICAL SUM
        // ---------------------------------------------------------------------
        let mut new_stage3 = StageReg3::default();
        if self.pipe_stage2.valid {
            let s_curr = self.pipe_stage2.state;
            let s_prev = self.pipe_stage2.prev_state;
            let s_prev2 = if self.pipe_stage3.valid {
                self.pipe_stage3.prev_state
            } else {
                s_prev
            };

            // Exact parity with training formula:
            let s_rotor = (((s_prev2 as usize)
                ^ ((s_prev as usize) << 1)
                ^ ((s_curr as usize) << 2))
                % NUM_STATES) as u8;

            let rotor_bias = &self.m_stage3[s_rotor as usize];

            let mut combined_scores = [0i32; NUM_STATES];
            for i in 0..NUM_STATES {
                combined_scores[i] = self.pipe_stage2.scores[i] + (rotor_bias[i] as i32);
            }

            new_stage3 = StageReg3 {
                valid: true,
                char: self.pipe_stage2.char,
                state: s_curr,
                prev_state: s_prev,
                prev_state2: s_prev2,
                scores: combined_scores,
            };
        }

        // ---------------------------------------------------------------------
        // TACT 2 (CYCLE 2): 2ND-ORDER TRIGRAM WIRE-SHIFT RESONANCE
        // ---------------------------------------------------------------------
        let mut new_stage2 = StageReg2::default();
        if self.pipe_stage1.valid {
            let s_curr = self.pipe_stage1.state;
            let s_prev = if self.pipe_stage2.valid {
                self.pipe_stage2.state
            } else {
                s_curr
            };

            // Exact parity with training formula:
            let s_perm = (((s_prev as usize) ^ ((s_curr as usize) << 1)) % NUM_STATES) as u8;

            let bigram_scores = &self.m_stage1[s_curr as usize];
            let trigram_scores = &self.m_stage2[s_perm as usize];

            let mut scores_s2 = [0i32; NUM_STATES];
            for i in 0..NUM_STATES {
                scores_s2[i] = (bigram_scores[i] as i32) + (trigram_scores[i] as i32);
            }

            new_stage2 = StageReg2 {
                valid: true,
                char: self.pipe_stage1.char,
                state: s_curr,
                prev_state: s_prev,
                scores: scores_s2,
            };
        }

        // ---------------------------------------------------------------------
        // TACT 1 (CYCLE 1): STATE INGESTION & 7-BIT DECODE
        // ---------------------------------------------------------------------
        let new_stage1 = if in_valid {
            StageReg1 {
                valid: true,
                char: in_char,
                state: char_to_state(in_char),
            }
        } else {
            StageReg1::default()
        };

        // Advance pipeline simultaneously on clock edge
        self.pipe_stage1 = new_stage1;
        self.pipe_stage2 = new_stage2;
        self.pipe_stage3 = new_stage3;

        out_result
    }

    /// Feeds prompt string through the pipeline and predicts the next character.
    pub fn predict_next_char(&mut self, prompt: &str) -> char {
        self.flush_pipeline();
        let mut last_pred = ' ';

        for ch in prompt.chars() {
            let out = self.clock_tick(true, ch);
            if out.valid {
                last_pred = out.predicted_char;
            }
        }

        // Flush remaining 3 pipeline stages with NOP
        for _ in 0..3 {
            let out = self.clock_tick(false, ' ');
            if out.valid {
                last_pred = out.predicted_char;
            }
        }

        last_pred
    }

    /// Serializes all 4 stages into a continuous 35,344-byte slice.
    pub fn to_bytes(&self) -> Vec<u8> {
        let mut bytes = Vec::with_capacity(FOUR_TACT_SIZE);
        for row in self.m_stage1.iter() {
            bytes.extend_from_slice(row);
        }
        for row in self.m_stage2.iter() {
            bytes.extend_from_slice(row);
        }
        for row in self.m_stage3.iter() {
            bytes.extend_from_slice(row);
        }
        for row in self.m_stage4.iter() {
            bytes.extend_from_slice(row);
        }
        bytes
    }

    /// Deserializes 35,344 bytes into the 4 stages.
    pub fn load_from_bytes(&mut self, data: &[u8]) -> Result<(), String> {
        if data.len() < FOUR_TACT_SIZE {
            return Err(format!(
                "Invalid 4-tact matrix byte size: expected {}, got {}",
                FOUR_TACT_SIZE,
                data.len()
            ));
        }

        let mut offset = 0;
        for row in self.m_stage1.iter_mut() {
            row.copy_from_slice(&data[offset..offset + NUM_STATES]);
            offset += NUM_STATES;
        }
        for row in self.m_stage2.iter_mut() {
            row.copy_from_slice(&data[offset..offset + NUM_STATES]);
            offset += NUM_STATES;
        }
        for row in self.m_stage3.iter_mut() {
            row.copy_from_slice(&data[offset..offset + NUM_STATES]);
            offset += NUM_STATES;
        }
        for row in self.m_stage4.iter_mut() {
            row.copy_from_slice(&data[offset..offset + NUM_STATES]);
            offset += NUM_STATES;
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_cayley_latin_square_verification() {
        assert!(verify_latin_square(3, 5, 7));
        assert!(verify_latin_square(7, 11, 13));
        // alpha=2 shares factor with 94 (94 = 2 * 47), must fail
        assert!(!verify_latin_square(2, 5, 7));
    }

    #[test]
    fn test_char_state_roundtrip() {
        for ascii in ASCII_START..=ASCII_END {
            let ch = ascii as char;
            let st = char_to_state(ch);
            let back = state_to_char(st);
            assert_eq!(ch, back);
        }
    }

    #[test]
    fn test_4tact_pipeline_learning_and_inference() {
        let mut pipe = FourTactPipeline94::new();
        pipe.train_sequence("fn quantum_compute() -> u64 { 42 }");
        pipe.train_sequence("fn quantum_compute() -> u64 { 42 }");

        let pred = pipe.predict_next_char("fn quantum_comput");
        assert_eq!(pred, 'e');
    }

    #[test]
    fn test_matrix_bytes_serialization() {
        let mut pipe = FourTactPipeline94::new();
        pipe.train_sequence("hello world");
        let bytes = pipe.to_bytes();
        assert_eq!(bytes.len(), FOUR_TACT_SIZE);

        let mut loaded = FourTactPipeline94::new();
        loaded.load_from_bytes(&bytes).unwrap();
        assert_eq!(loaded.to_bytes(), bytes);
    }
}
