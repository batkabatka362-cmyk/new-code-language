    pub fn mangle_type_name(s: &str) -> String {
        let trimmed = s.trim();
        if !trimmed.contains('<') {
            return trimmed.to_string();
        }
        let mut res = String::with_capacity(trimmed.len());
        for c in trimmed.chars() {
            match c {
                '<' | ',' | ' ' | ';' => {
                    if !res.ends_with('_') {
                        res.push('_');
                    }
                }
                '>' => {}
                _ => res.push(c),
            }
        }
        res.trim_end_matches('_').to_string()
    }

    fn map_type(cron_type: &str) -> String {
        let mut trimmed = cron_type.trim();
        // Strip spatial memory domain annotations, e.g. "@sram(bank=0) i2" -> "i2"
        if trimmed.starts_with('@') {
            if let Some(space_idx) = trimmed.find(' ') {
                trimmed = trimmed[space_idx..].trim();
            }
        }
        trimmed = trimmed
            .trim_start_matches("linear ")
            .trim_start_matches("lin ")
            .trim();

        if trimmed == "tile4x4_f32" || trimmed == "tile<4, 4, f32>" || trimmed == "tile<4,4,f32>" {
            return "cron_tile4x4_f32_t".to_string();
        }
        if trimmed == "tile4x4_i32" || trimmed == "tile<4, 4, i32>" || trimmed == "tile<4,4,i32>" {
            return "cron_tile4x4_i32_t".to_string();
        }
        if trimmed == "tile16x16_i2" || trimmed == "tile<16, 16, i2>" || trimmed == "tile<16,16,i2>" {
            return "cron_tile16x16_i2_t".to_string();
        }

        if trimmed.starts_with("channel<") || trimmed.starts_with("Channel<")
            || trimmed.starts_with("channel_") || trimmed.starts_with("Channel_")
            || trimmed == "channel" || trimmed == "Channel" {
            return "cron_channel_t*".to_string();
        }
        if trimmed.starts_with("fiber<") || trimmed.starts_with("Fiber<")
            || trimmed.starts_with("fiber_") || trimmed.starts_with("Fiber_")
            || trimmed == "fiber" || trimmed == "Fiber" || trimmed == "FiberHandle" {
            return "cron_fiber_t*".to_string();
        }

        if trimmed.starts_with("tensor<") || trimmed.starts_with("tensor") {
            return "cron_tensor_f32_t".to_string();
        }

        if trimmed.contains('<') {
            let mangled = Self::mangle_type_name(trimmed);
            return format!("struct {}", mangled);
        }

        match trimmed {
            "i2" | "i4" => "int8_t".to_string(),
            "f4" | "f8" | "f16" | "bf16" => "float".to_string(),
            "i8" => "int8_t".to_string(),
            "i16" => "int16_t".to_string(),
            "i32" | "int" => "int32_t".to_string(),
            "i64" => "int64_t".to_string(),
            "u8" => "uint8_t".to_string(),
            "u16" => "uint16_t".to_string(),
            "u32" => "uint32_t".to_string(),
            "u64" => "uint64_t".to_string(),
            "f32" | "float" => "float".to_string(),
            "f64" => "double".to_string(),
            "bool" => "bool".to_string(),
            "string" => "const char*".to_string(),
            "wave_t" => "cron_wave_t".to_string(),
            "ext_addr_t" => "cron_ext_addr_t".to_string(),
            "spk_stamp" => "cron_spk_stamp_t".to_string(),
            "rev_t" => "cron_rev_t".to_string(),
            "TorusCoord" => "cron_torus_coord_t".to_string(),
            "vec4_i8" | "topo_coord" => "const void*".to_string(),
            "vec4f" => "cron_vec4f".to_string(),
            "vec8f" => "cron_vec8f".to_string(),
            "vec16f" => "cron_vec16f".to_string(),
            "vec4i" => "cron_vec4i".to_string(),
            "vec8i" => "cron_vec8i".to_string(),
            "void" | "()" => "void".to_string(),
            other => {
                if other.starts_with('(') && other.ends_with(')') {
                    // Tuple type like (u32, u32)
                    "cron_tuple_t".to_string()
                } else if other.starts_with('[') && other.ends_with(']') {
                    // Array type like [i32; 4]
                    "const void*".to_string()
                } else if other.starts_with("struct ") {
                    other.to_string()
                } else {
                    format!("struct {}", other)
                }
            }
        }
    }

    fn emit_struct(&mut self, s: &StructDecl) {
        let clean_name = Self::mangle_type_name(&s.name);
        self.emit_line(&format!("typedef struct {} {{", clean_name));
        self.indent_level += 1;
        for (field_name, field_type) in &s.fields {
            let c_type = Self::map_type(field_type);
            self.emit_line(&format!("{} {};", c_type, field_name));
        }
        self.indent_level -= 1;
        self.emit_line(&format!("}} {};", clean_name));
        self.emit_line("");
        self.declared_structs.insert(clean_name);
    }

