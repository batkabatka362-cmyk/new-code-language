/// Writes the full 11-file DPSTA ASIC Tapeout Package (RTL + OpenLane Sky130 GDSII configs + scripts).
pub fn export_dpsta_asic_tapeout(dir: &Path) -> std::io::Result<Vec<String>> {
    let mut files = export_dpsta_rtl_package(dir)?;

    let openlane_json = generate_dpsta_openlane_config();
    let pin_order = generate_dpsta_pin_order();
    let run_sh = generate_dpsta_openlane_run_sh();
    let yosys_ys = generate_dpsta_yosys_synth_ys();

    let json_p = dir.join("config.json");
    let pin_p = dir.join("pin_order.cfg");
    let run_p = dir.join("run_openlane.sh");
    let yosys_p = dir.join("synth_yosys.ys");

    fs::write(&json_p, &openlane_json)?;
    fs::write(&pin_p, &pin_order)?;
    fs::write(&run_p, &run_sh)?;
    fs::write(&yosys_p, &yosys_ys)?;

    files.push(json_p.display().to_string());
    files.push(pin_p.display().to_string());
    files.push(run_p.display().to_string());
    files.push(yosys_p.display().to_string());

    Ok(files)
}

